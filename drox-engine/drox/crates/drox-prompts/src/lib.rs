//! Catalogue central des prompts Drox injectés au LLM.
//!
//! Doc humaine : `README.md`, `docs/injection-map.md`, `docs/journal.md`,
//! `docs/adding.md`, `docs/verification.md` à la racine de ce crate.
//!
//! ## Notation d'intention
//!
//! Chaque entrée [`PromptEntry`] déclare `id`, `intent`, `strength`, `audience`,
//! `when`, `topics`, `claims` et le `body`. Les **claims** (`clé=valeur`) permettent
//! un lint strict anti-contradiction (`catalog_lint`).
//!
//! | Module | Rôle |
//! |--------|------|
//! | [`entry`] | Types de notation |
//! | [`catalog`] | Registre de toutes les entrées |
//! | [`core`] | `CORE_SYSTEM_PROMPT` |
//! | [`session`] | Suppléments session (hors-WS, Explore, thinking, professeur) |
//! | [`runtime`] | Nudges boucle agent (S-5, DOC, kickoff, …) |
//! | [`gates`] | Nudges done / testing / intent-write / loops / todos |
//! | [`blocks`] | Messages de refus hard-gate (todo / professeur / phase) |
//! | [`compaction`] | Prompt système compaction mémoire |
//! | [`explore`] | System Explore + cascade visuelle (`explore/cascade/`) |
//! | [`tools`] | Descriptions d'outils exposées au LLM |
//! | [`model_questions`] | Asks one-shot (boot intent multi-bool) |
//! | [`lint`] | Vérification claims / doublons d'id |

