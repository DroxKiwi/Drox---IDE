/// Toutes les fiches actuellement dans le catalogue.
#[must_use]
pub fn all_entries() -> &'static [PromptEntry] {
	static ALL: OnceLock<Vec<PromptEntry>> = OnceLock::new();
	ALL.get_or_init(|| {
		let mut out = Vec::with_capacity(NON_TOOL_ENTRIES.len() + all_tool_entries().len());
		out.extend_from_slice(&NON_TOOL_ENTRIES);
		out.extend_from_slice(all_tool_entries());
		out
	})
	.as_slice()
}

/// Lookup par `id`.
#[must_use]
pub fn entry_by_id(id: &str) -> Option<&'static PromptEntry> {
	all_entries().iter().find(|e| e.id == id)
}

